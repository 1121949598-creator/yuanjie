import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const out='E:/GPT工作区/AIC-安全/.work/pdf-check';await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1063,height:704},acceptDownloads:true});const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{window.print=()=>{};});
await page.goto('http://127.0.0.1:8002/app/?v=5.2#/scan/64a69a17ba0a4504/report?mode=project');
await page.getByRole('button',{name:'下载 PDF',exact:true}).waitFor();
const box=await page.locator('.task-pet').boundingBox();
if(box.x+box.width>230)throw Error('Pet still overlaps main content');
await page.getByRole('button',{name:'打印',exact:true}).click();
await page.getByRole('status').filter({hasText:'如果没有出现打印窗口'}).waitFor();
if((await page.locator('.task-pet').innerText()).includes('不是 AI'))throw Error('Removed copy remains');
await page.locator('.task-pet .watercolor-cat').click();
await page.screenshot({path:out+'/sidebar-pet.png'});
const downloadPromise=page.waitForEvent('download',{timeout:60000});
await page.getByRole('button',{name:'下载 PDF',exact:true}).click();
const download=await downloadPromise;await download.saveAs(out+'/report.pdf');
await page.getByRole('status').filter({hasText:'PDF 已生成'}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(500);
await page.screenshot({path:out+'/mobile-report.png'});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2))throw Error('Mobile overflow');
await fs.writeFile(out+'/verification.json',JSON.stringify({passed:!errors.length,errors,downloadName:download.suggestedFilename(),sidebarPet:true,printFallback:true},null,2));
console.log(JSON.stringify({passed:!errors.length,errors}));await browser.close();if(errors.length)process.exitCode=1;
