import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve(process.argv[2]);
await fs.mkdir(output, {recursive: true});
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
const page = await browser.newPage({viewport: {width:1440,height:960}, deviceScaleFactor:1});
const failures = [];
page.on('pageerror', error => failures.push(error.message));
const base = 'http://127.0.0.1:8002/app/#';
async function open(route, file) {
  await page.goto(`${base}${route}`);
  await page.waitForTimeout(1000);
  await page.screenshot({path: path.join(output,file),fullPage:false});
}
await open('/', '01-home.png');
await page.getByRole('link',{name:'检查下载的工具',exact:true}).first().waitFor();
await page.getByRole('link',{name:'检查自己的项目',exact:true}).first().waitFor();
await page.getByRole('link',{name:/专业用户 · Agent 专项审查/}).waitFor();
const start = await page.locator('[data-testid="river-boat"]').getAttribute('transform');
await page.waitForTimeout(1000);
const end = await page.locator('[data-testid="river-boat"]').getAttribute('transform');
if(start === end) failures.push('Boat did not move');
await page.getByRole('button',{name:'暂停小船动画'}).click();
const stopped = await page.locator('[data-testid="river-boat"]').getAttribute('transform');
await page.waitForTimeout(300);
if(stopped !== await page.locator('[data-testid="river-boat"]').getAttribute('transform')) failures.push('Pause failed');
const scans = [];
for (const [mode,scene] of [['download','install_precheck'],['project','release_precheck'],['agent','release_precheck']]) {
  await open(`/new?mode=${mode}`, `02-${mode}.png`);
  let sentScene;
  const handler = request => {if(request.method()==='POST' && request.url().endsWith('/api/scans')) sentScene=request.postData();};
  page.on('request',handler);
  const created = page.waitForResponse(response => response.url().endsWith('/api/scans') && response.request().method()==='POST',{timeout:60000});
  await page.getByRole('button',{name:'运行示例'}).first().click();
  const response = await created;
  const data = await response.json();
  const saved = await page.request.get(`http://127.0.0.1:8002/api/scans/${data.scan_id}`).then(r=>r.json());
  if(response.status() !== 201 || saved.metadata.component_security_scene !== scene) failures.push(`Wrong persisted scene or failed real scan: ${mode}`);
  await page.waitForURL(/\/scan\//,{timeout:30000});
  await page.getByText('正在读取扫描结果',{exact:true}).waitFor({state:'hidden'});
  await page.waitForTimeout(800);
  await page.screenshot({path:path.join(output,`03-result-${mode}.png`)});
  if(mode==='agent' && !page.url().includes('/agents')) failures.push('Agent did not open specialist result');
  if(mode==='download' && !page.url().includes('/components')) failures.push('Download did not open capability result');
  scans.push({mode,scene,id:data.scan_id,status:response.status(),url:page.url()});
  page.off('request',handler);
}
await open('/mascot','04-mascot-eight-states.png');
if(await page.locator('.mascot-poses [data-mood]').count()!==8) failures.push('Missing mascot states');
await open('/history','05-history.png');
await page.setViewportSize({width:390,height:844});
await open('/','06-mobile-home.png');
await open('/new?mode=download','07-mobile-download.png');
if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2)) failures.push('Mobile horizontal overflow');
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto(`${base}/`);await page.waitForTimeout(500);
const reducedStart = await page.locator('[data-testid="river-boat"]').getAttribute('transform');
await page.waitForTimeout(400);
if(reducedStart !== await page.locator('[data-testid="river-boat"]').getAttribute('transform')) failures.push('Reduced motion failed');
await fs.writeFile(path.join(output,'browser-verification.json'),JSON.stringify({passed:failures.length===0,failures,scans,boatMoved:start!==end},null,2));
await browser.close();
console.log(JSON.stringify({passed:failures.length===0,failures,scans,output},null,2));
if(failures.length) process.exitCode=1;
